import { applyEdits, type FormattingOptions, modify, parse } from "jsonc-parser";
import { needsShell, splitCommandLine } from "../core/command/commandLine";
import type { ColumnConfig, SectionConfig } from "../core/config/schema";
import { slug } from "../core/view/merge";
import type { SectionPrefs } from "../shared/protocol";

const FORMAT: FormattingOptions = { insertSpaces: true, tabSize: 2, eol: "\n" };
/** Implicit table columns, absent from config. */
const IMPLICIT = new Set(["select", "status", "name", "namespace"]);

const columnId = (c: ColumnConfig) => c.id ?? slug(c.title);

/**
 * Column differences (order / visibility / width) relative to the original section.
 * `extends`: patches merge by ID (reordering = remove, then re-add full definitions); `full`: complete column list.
 */
export function columnsPatch(section: SectionConfig, prefs: SectionPrefs, target: "extends" | "full"): object[] {
  const base = section.columns;
  const baseIds = base.map(columnId);
  const order = (prefs.columnOrder ?? baseIds).filter((id) => !IMPLICIT.has(id) && baseIds.includes(id));
  const ordered = [...order, ...baseIds.filter((id) => !order.includes(id))];
  const hidden = new Set(prefs.hidden ?? []);
  const widths = prefs.widths ?? {};
  const full = (id: string): object => {
    const c = base.find((x) => columnId(x) === id)!;
    const width = widths[id] ?? c.width;
    return {
      ...c,
      id,
      hidden: hidden.has(id) || (prefs.hidden === undefined && c.hidden),
      ...(width ? { width } : {}),
    };
  };
  const reordered = ordered.join("\n") !== baseIds.join("\n");
  if (target === "full") return ordered.map(full);
  if (reordered) return [...baseIds.map((id) => ({ id, remove: true })), ...ordered.map(full)];
  const out: object[] = [];
  for (const c of base) {
    const id = columnId(c);
    const diff: Record<string, unknown> = {};
    const w = widths[id];
    if (w !== undefined && w !== c.width) diff["width"] = w;
    if (prefs.hidden !== undefined && hidden.has(id) !== c.hidden) diff["hidden"] = hidden.has(id);
    if (Object.keys(diff).length > 0) out.push({ id, ...diff });
  }
  return out;
}

interface ViewEntry {
  id?: string;
  extends?: string;
  sections?: { id?: string }[];
}

/** Write a section's columns to an override file (preserving comments/formatting with jsonc-parser's `modify`). */
export function upsertSectionColumns(
  text: string | undefined,
  viewId: string,
  sectionId: string,
  columns: readonly object[],
): string {
  if (text === undefined || text.trim() === "") {
    return `${JSON.stringify({ version: 1, views: [{ extends: viewId, sections: [{ id: sectionId, columns }] }] }, null, 2)}\n`;
  }
  const root = (parse(text) ?? {}) as { views?: ViewEntry[] };
  const views = root.views ?? [];
  const index = views.findIndex((v) => v.extends === viewId || (v.id === viewId && v.extends === undefined));
  const edit = (path: (string | number)[], value: unknown, insert = false) =>
    applyEdits(
      text,
      modify(text, path, value, { formattingOptions: FORMAT, ...(insert ? { isArrayInsertion: true } : {}) }),
    );
  if (!root.views) return edit(["views"], [{ extends: viewId, sections: [{ id: sectionId, columns }] }]);
  if (index < 0)
    return edit(["views", views.length], { extends: viewId, sections: [{ id: sectionId, columns }] }, true);
  const sections = views[index]!.sections;
  if (!sections) return edit(["views", index, "sections"], [{ id: sectionId, columns }]);
  const s = sections.findIndex((x) => x.id === sectionId);
  if (s < 0) return edit(["views", index, "sections", sections.length], { id: sectionId, columns }, true);
  return edit(["views", index, "sections", s, "columns"], columns);
}

/** New override file content for "Edit view config" on built-in/preset views. */
export function viewOverrideText(viewId: string): string {
  return `${JSON.stringify({ version: 1, views: [{ extends: viewId }] }, null, 2)}\n`;
}

/** Template file generated by the "Create custom view" wizard: one section per selected kind. */
export function customViewText(
  id: string,
  title: string,
  kinds: readonly { group: string; kind: string; plural: string }[],
): string {
  const sections = kinds.map((k) => ({
    id: k.plural,
    title: `${k.kind}s`,
    resources: [{ group: k.group, kind: k.kind }],
    columns: [
      { title: "Ready", path: "$.status.conditions[?(@.type=='Ready')].status", render: "status" },
      { title: "Age", path: "$.metadata.creationTimestamp", render: "age" },
    ],
  }));
  return `${JSON.stringify({ version: 1, views: [{ id, title, icon: "list-tree", sections }] }, null, 2)}\n`;
}

/** How to populate a `${input:<id>}` parameter in a wizard-created snippet. */
export type SnippetParam =
  | { readonly id: string; readonly type: "text"; readonly secret?: boolean }
  | { readonly id: string; readonly type: "options"; readonly options: readonly string[] }
  | { readonly id: string; readonly type: "resource"; readonly group: string; readonly kind: string };

export interface SnippetDraft {
  readonly id: string;
  readonly title: string;
  readonly group?: string;
  readonly commandLine: string;
  readonly target: "namespace" | "context";
  readonly runIn: "terminal" | "process";
  readonly params: readonly SnippetParam[];
  readonly platform: string;
}

const CONTEXT_FLAGS: Readonly<Record<string, string>> = {
  kubectl: "--context",
  flux: "--context",
  helm: "--kube-context",
};
const NAMESPACE_FLAGS = ["-n", "--namespace", "-A", "--all-namespaces"];

const hasFlag = (args: readonly string[], flags: readonly string[]) =>
  args.some((a) => flags.some((f) => a === f || a.startsWith(`${f}=`)));

/**
 * Command (snippet) from the "Create snippet" wizard. Shell syntax runs via `sh -c` (PowerShell on Windows);
 * kubectl/helm/flux automatically receive context flags (and namespace flags for namespace targets) so commands use
 * the context selected in K8s View rather than kubeconfig's current-context.
 */
export function snippetCommand(d: SnippetDraft): Record<string, unknown> {
  let command: string;
  let args: string[];
  if (needsShell(d.commandLine)) {
    [command, args] =
      d.platform === "win32"
        ? ["powershell.exe", ["-NoProfile", "-Command", d.commandLine]]
        : ["sh", ["-c", d.commandLine]];
  } else {
    const argv = splitCommandLine(d.commandLine);
    if (argv.length === 0) throw new SyntaxError("Empty command line");
    [command, ...args] = argv as [string, ...string[]];
    const tool =
      command
        .replace(/\.exe$/i, "")
        .split(/[\\/]/)
        .pop() ?? command;
    const contextFlag = CONTEXT_FLAGS[tool];
    if (contextFlag) {
      const sep = args.indexOf("--");
      const flags = sep < 0 ? args : args.slice(0, sep);
      const rest = sep < 0 ? [] : args.slice(sep);
      const extra: string[] = [];
      if (d.target === "namespace" && !hasFlag(flags, NAMESPACE_FLAGS))
        extra.push("-n", "${namespace|default:default}");
      if (!hasFlag(flags, [contextFlag])) extra.push(contextFlag, "${context}");
      args = [...flags, ...extra, ...rest];
    }
  }
  const inputs = d.params.map((p) => {
    const title = p.id.replace(/[-_.]+/g, " ").replace(/^./, (c) => c.toUpperCase());
    switch (p.type) {
      case "options":
        return { id: p.id, type: "pick", title, options: [...p.options] };
      case "resource":
        return { id: p.id, type: "pick", title, fromKind: { group: p.group, kind: p.kind } };
      default:
        return { id: p.id, type: "prompt", title, ...(p.secret ? { secret: true } : {}) };
    }
  });
  return {
    id: d.id,
    title: d.title,
    ...(d.group ? { group: d.group } : {}),
    icon: "terminal",
    target: d.target,
    ...(inputs.length > 0 ? { inputs } : {}),
    run:
      d.runIn === "terminal" ? { type: "terminal", name: d.title, command, args } : { type: "process", command, args },
  };
}

/** Append a command to `commands` (create a new file if empty); return new content and the command's position. */
export function appendCommand(text: string | undefined, command: object): { text: string; index: number } {
  if (text === undefined || text.trim() === "") {
    return { text: `${JSON.stringify({ version: 1, commands: [command] }, null, 2)}\n`, index: 0 };
  }
  const root = (parse(text) ?? {}) as { commands?: unknown[] };
  if (!Array.isArray(root.commands)) {
    return { text: applyEdits(text, modify(text, ["commands"], [command], { formattingOptions: FORMAT })), index: 0 };
  }
  const index = root.commands.length;
  const edits = modify(text, ["commands", index], command, { formattingOptions: FORMAT, isArrayInsertion: true });
  return { text: applyEdits(text, edits), index };
}

/** Delete command `index` from `commands` (preserving comments and formatting elsewhere). */
export function removeCommand(text: string, index: number): string {
  return applyEdits(text, modify(text, ["commands", index], undefined, { formattingOptions: FORMAT }));
}
